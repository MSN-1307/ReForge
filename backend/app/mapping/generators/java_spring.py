def _controller(routes: List[UniversalRoute], model_name: str, project: UniversalProject) -> Tuple[str, str]:
    method_annots = {"GET": "@GetMapping", "POST": "@PostMapping", "PUT": "@PutMapping",
                     "DELETE": "@DeleteMapping", "PATCH": "@PatchMapping"}

    # Find common base path
    paths = [r.path for r in routes]
    base_path = "/api"
    if paths:
        parts = paths[0].rstrip("/").split("/")
        if len(parts) >= 3:
            base_path = "/" + "/".join(parts[1:3]).split("{")[0].rstrip("/")

    methods_code = []
    for idx, r in enumerate(routes):
        annot = method_annots.get(r.method, "@GetMapping")
        # sub path relative to base
        sub = r.path
        if base_path != "/" and sub.startswith(base_path):
            sub = sub[len(base_path):] or ""

        args = []
        for p in r.path_params:
            args.append(f"@PathVariable Long {p}")
        if r.method in ("POST", "PUT", "PATCH"):
            args.append(f"@RequestBody {model_name} payload")
        args_str = ", ".join(args)
        sub_expr = f'("{sub}")' if sub else ""
        sc_annot = '@ResponseStatus(HttpStatus.CREATED)\n    ' if r.status_code == 201 else ""

        if r.method == "GET" and not r.path_params:
            body = f"return ResponseEntity.ok(repository.findAll());"
            ret = f"ResponseEntity<java.util.List<{model_name}>>"
            mname = "getAll"
        elif r.method == "GET":
            p0 = r.path_params[0] if r.path_params else "id"
            body = f"return repository.findById({p0}).map(ResponseEntity::ok).orElse(ResponseEntity.notFound().build());"
            ret = f"ResponseEntity<{model_name}>"
            mname = "getById"
        elif r.method == "POST":
            body = f"{model_name} saved = repository.save(payload);\n        return ResponseEntity.status(HttpStatus.CREATED).body(saved);"
            ret = f"ResponseEntity<{model_name}>"
            mname = "create"
        elif r.method in ("PUT", "PATCH"):
            p0 = r.path_params[0] if r.path_params else "id"
            body = f"if (!repository.existsById({p0})) return ResponseEntity.notFound().build();\n        payload.setId({p0});\n        return ResponseEntity.ok(repository.save(payload));"
            ret = f"ResponseEntity<{model_name}>"
            mname = "update"
        elif r.method == "DELETE":
            p0 = r.path_params[0] if r.path_params else "id"
            body = f"if (!repository.existsById({p0})) return ResponseEntity.notFound().build();\n        repository.deleteById({p0});\n        return ResponseEntity.noContent().build();"
            ret = "ResponseEntity<Void>"
            mname = "delete"
        else:
            body = "return ResponseEntity.ok().build();"
            ret = "ResponseEntity<Object>"
            mname = f"handle{idx}"

        methods_code.append(f"""    {annot}{sub_expr}
    {sc_annot}public {ret} {mname}({args_str}) {{
        {body}
    }}
""")

    ctrl_name = model_name
    content = f"""package {PACKAGE}.controller;

import {PACKAGE}.entity.{model_name};
import {PACKAGE}.repository.{model_name}Repository;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import java.util.List;

/**
 * REST Controller migrated from {project.source_language}/{project.source_framework} by ReForge
 */
@RestController
@RequestMapping("{base_path}")
@CrossOrigin(origins = "*")
public class {ctrl_name}Controller {{

    private final {model_name}Repository repository;

    public {ctrl_name}Controller({model_name}Repository repository) {{
        this.repository = repository;
    }}

{"".join(methods_code)}
}}
"""
    return f"src/main/java/{PACKAGE_PATH}/controller/{ctrl_name}Controller.java", content


def _dockerfile() -> Tuple[str, str]:
    content = """# Multi-stage Dockerfile generated by ReForge
FROM maven:3.9.6-eclipse-temurin-17 AS build
WORKDIR /app
COPY pom.xml .
RUN mvn dependency:go-offline -B
COPY src ./src
RUN mvn package -DskipTests

FROM eclipse-temurin:17-jre-alpine
WORKDIR /app
COPY --from=build /app/target/*.jar app.jar
EXPOSE 8080
ENTRYPOINT ["java", "-jar", "app.jar"]
"""
    return "Dockerfile", content


def _docker_compose(include_redis: bool) -> Tuple[str, str]:
    redis_svc = ""
    redis_env = ""
    if include_redis:
        redis_svc = """
  redis:
    image: redis:7-alpine
    ports:
      - "6379:6379"
    restart: unless-stopped"""
        redis_env = "\n      - SPRING_REDIS_HOST=redis\n      - SPRING_REDIS_PORT=6379"
    content = f"""version: '3.8'
services:
  app:
    build: .
    ports:
      - "8080:8080"
    environment:
      - SPRING_PROFILES_ACTIVE=prod{redis_env}
    restart: unless-stopped{redis_svc}
"""
    return "docker-compose.yml", content



from app.parser.universal_parser import UniversalProject, UniversalRoute, UniversalModel, UniversalField

PACKAGE = "com.reforge.app"
PACKAGE_PATH = PACKAGE.replace(".", "/")

TYPE_MAP = {
    "String": "String",
    "Integer": "Long",
    "Float": "Double",
    "Boolean": "Boolean",
    "DateTime": "java.time.LocalDateTime",
    "List": "java.util.List<String>",
}

def generate_spring_boot(project: UniversalProject, upgrades: List[str] = None, target_dir: Path = None) -> List[Tuple[str, str]]:
    """Returns list of (relative_path, content) tuples for all generated files."""
    upgrades = upgrades or []
    files = []
    files.append(_pom_xml(project, upgrades))
    files.append(_application_properties())
    files.append(_main_application())
    for model in project.models:
        files.append(_entity(model))
        files.append(_repository(model))
    # Group routes by model
    model_names = [m.name for m in project.models]
    model_name = model_names[0] if model_names else "Item"
    if project.routes:
        files.append(_controller(project.routes, model_name, project))
    if "docker" in upgrades:
        files.append(_dockerfile())
        files.append(_docker_compose("redis" in upgrades))
    if "openapi" in upgrades:
        files.append(_openapi_config())
    if "redis" in upgrades:
        files.append(_redis_config())
    return files


def _java_type(t: str) -> str:
    return TYPE_MAP.get(t, "String")



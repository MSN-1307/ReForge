def _entity(model: UniversalModel) -> Tuple[str, str]:
    fields_code = ["    @Id\n    @GeneratedValue(strategy = GenerationType.IDENTITY)\n    private Long id;\n"]
    getset = ["""    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }
"""]
    for f in model.fields:
        if f.name.lower() in ("id", "_id"):
            continue
        jtype = _java_type(f.type)
        null_str = "false" if f.required else "true"
        fields_code.append(f"    @Column(nullable = {null_str})\n    private {jtype} {f.name};\n")
        cap = f.name[0].upper() + f.name[1:]
        getset.append(f"""    public {jtype} get{cap}() {{ return {f.name}; }}
    public void set{cap}({jtype} {f.name}) {{ this.{f.name} = {f.name}; }}
""")

    content = f"""package {PACKAGE}.entity;

import jakarta.persistence.*;
import java.io.Serializable;

/**
 * Entity migrated from {model.file} by ReForge
 */
@Entity
@Table(name = "{model.table_name}")
public class {model.name} implements Serializable {{

{"".join(fields_code)}
    public {model.name}() {{}}

{"".join(getset)}
}}
"""
    return f"src/main/java/{PACKAGE_PATH}/entity/{model.name}.java", content


